size_check = ->(s){s.size == 48}
split = ->(s){(0...6).map{|i| s[i*8,8]}}
checker = [
  ->(s){s.chars.map{|c| c.ord^0xfe} == [0xad,0xbb,0xbd,0xbd,0xb1,0xb0,0x85,0xad]},
  ->(s){s.chars.map{|c| c.ord^0x5f} == [0x37,0x6c,0x00,0x28,0x6f,0x2a,0x33,0x3b]},
  ->(s){s.chars.map{|c| c.ord^0xa2} == [0xfd,0xcc,0x91,0xd4,0x91,0xd0,0xfd,0xd1]},
  ->(s){s.chars.map{|c| c.ord^0x40} == [0x74,0x39,0x1f,0x37,0x28,0x73,0x32,0x73]},
  ->(s){s.chars.map{|c| c.ord^0x9c} == [0xc3,0xef,0xf4,0xaf,0xc3,0xff,0xa8,0xf1]},
  ->(s){s.chars.map{|c| c.ord^0x2d} == [0x1e,0x72,0x4b,0x5f,0x1d,0x40,0x50,0x27]}
]

if size_check.call($input) and split.call($input).zip(checker).map{|s, f| f.call(s)}.all?
  puts 'Correct!'
else
  puts 'Incorrect...'
end
